package org.opennms.web.rest.v2.model;

/**
 * REST payload for an OpenConfig target binding (NMS-19857).
 *
 * <p>{@code username}/{@code password} are write-only: on create/update they are stored in the
 * Secure Credentials Vault and never returned. {@code credentialRef}/{@code tlsRef} expose only the
 * vault alias, never the secret.</p>
 */
public class OpenConfigTargetDto {

    private Integer id;
    private Integer profileId;
    private String name;
    private String matchType;
    private String filterRule;
    private String nodeIds;
    private Integer port;
    private String credentialRef;
    private String tlsRef;
    private Boolean enabled;

    // Write-only credential input.
    private String username;
    private String password;

    public Integer getId() {
        return id;
    }

    public void setId(Integer id) {
        this.id = id;
    }

    public Integer getProfileId() {
        return profileId;
    }

    public void setProfileId(Integer profileId) {
        this.profileId = profileId;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getMatchType() {
        return matchType;
    }

    public void setMatchType(String matchType) {
        this.matchType = matchType;
    }

    public String getFilterRule() {
        return filterRule;
    }

    public void setFilterRule(String filterRule) {
        this.filterRule = filterRule;
    }

    public String getNodeIds() {
        return nodeIds;
    }

    public void setNodeIds(String nodeIds) {
        this.nodeIds = nodeIds;
    }

    public Integer getPort() {
        return port;
    }

    public void setPort(Integer port) {
        this.port = port;
    }

    public String getCredentialRef() {
        return credentialRef;
    }

    public void setCredentialRef(String credentialRef) {
        this.credentialRef = credentialRef;
    }

    public String getTlsRef() {
        return tlsRef;
    }

    public void setTlsRef(String tlsRef) {
        this.tlsRef = tlsRef;
    }

    public Boolean getEnabled() {
        return enabled;
    }

    public void setEnabled(Boolean enabled) {
        this.enabled = enabled;
    }

    public String getUsername() {
        return username;
    }

    public void setUsername(String username) {
        this.username = username;
    }

    public String getPassword() {
        return password;
    }

    public void setPassword(String password) {
        this.password = password;
    }
}
